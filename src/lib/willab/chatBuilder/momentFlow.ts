export type QuestionId = (typeof ENGAGEMENT_QUESTIONS)[number]["id"];
export type CheckpointId = (typeof CHECKPOINTS)[number]["id"];
export type MomentId = (typeof MOMENTS)[number]["id"];
export type InterventionId = (typeof INTERVENTIONS)[number]["id"];
export type MatchShapeId = (typeof MATCH_SHAPES)[number]["id"];

export type MomentMapping = {
  id: string;
  moment: MomentId;
  intervention: InterventionId;
  /** 0 to 100. The placeholder pattern must reach this before it fires. */
  threshold: number;
  /** 0 to 100. How strongly it fires when the match is full. */
  intensity: number;
  on: boolean;
};

export type MomentConfig = {
  recordingSeconds: number;
  questions: Record<QuestionId, boolean>;
  voiceSample: boolean;
  checkpoints: Record<CheckpointId, boolean>;
  /** Which interventions the host attached to each checkpoint. */
  checkpointInterventions: Record<CheckpointId, InterventionId[]>;
  mappings: MomentMapping[];
  /** When true, Try opens the baseline. Off until the host saves it on. */
  meetVisitors: boolean;
};

export type SpeakerMoment = {
  answers: Partial<Record<QuestionId, string>>;
  voiceSample: boolean;
  recorded: boolean;
};

/** A fixed stand-in. It is not a measurement of anyone's voice. */
export const PLACEHOLDER_PATTERN: Record<MomentId, number> = {
  engagement: 70,
  arousal: 80,
  clarity: 40,
  context: 55,
};

export const PLACEHOLDER_SHAPE: MatchShapeId = "climb";

export const PLACEHOLDER_LINE = "Placeholder. This is not a reading of the recording. No model ran.";
export const AI_DISCLOSURE = "This feedback is generated by AI.";
export const PRIVACY_LINE = "Only you can see this. The host of this chat cannot.";

const THRESHOLD_WORD = [
  { word: "Loose", value: 30 },
  { word: "Usual", value: 50 },
  { word: "Strict", value: 70 },
] as const;

const INTENSITY_WORD = [
  { word: "Light", value: 35 },
  { word: "Steady", value: 60 },
  { word: "Strong", value: 90 },
] as const;

export function thresholdWord(value: number): (typeof THRESHOLD_WORD)[number]["word"] {
  return nearest(THRESHOLD_WORD, value).word;
}

export function intensityWord(value: number): (typeof INTENSITY_WORD)[number]["word"] {
  return nearest(INTENSITY_WORD, value).word;
}

export function nextThreshold(value: number): number {
  return cycle(THRESHOLD_WORD, value);
}

export function nextIntensity(value: number): number {
  return cycle(INTENSITY_WORD, value);
}

function nearest<T extends { value: number }>(rows: readonly T[], value: number): T {
  return rows.reduce((best, row) => (Math.abs(row.value - value) < Math.abs(best.value - value) ? row : best));
}

function cycle<T extends { value: number }>(rows: readonly T[], value: number): number {
  const at = rows.findIndex((row) => row.value === nearest(rows, value).value);
  return rows[(at + 1) % rows.length].value;
}

function mapping(id: string, moment: MomentId, intervention: InterventionId, threshold: number, intensity: number): MomentMapping {
  return { id, moment, intervention, threshold, intensity, on: true };
}

