/** One to five minutes. Never longer than five. */
export function clampRecordingSeconds(seconds: number): number {
  if (!Number.isFinite(seconds)) return RECORDING_MAX_SECONDS;
  const minutes = Math.round(seconds / 60);
  return Math.min(5, Math.max(1, minutes)) * 60;
}

function isId<T extends string>(ids: readonly T[], value: unknown): value is T {
  return typeof value === "string" && (ids as readonly string[]).includes(value);
}

function readMapping(value: unknown): MomentMapping | null {
  if (!value || typeof value !== "object") return null;
  const row = value as Partial<MomentMapping>;
  if (!isId(MOMENTS.map((m) => m.id), row.moment)) return null;
  if (!isId(INTERVENTIONS.map((m) => m.id), row.intervention)) return null;
  if (typeof row.threshold !== "number" || typeof row.intensity !== "number") return null;
  return {
    id: typeof row.id === "string" && row.id ? row.id : `${row.moment}-${row.intervention}`,
    moment: row.moment,
    intervention: row.intervention,
    threshold: Math.min(100, Math.max(0, row.threshold)),
    intensity: Math.min(100, Math.max(0, row.intensity)),
    on: row.on !== false,
  };
}

export function normaliseMomentConfig(value: unknown): MomentConfig {
  const base = defaultMomentConfig();
  if (!value || typeof value !== "object") return base;
  const got = value as Partial<MomentConfig>;
  const questions = { ...base.questions };
  for (const q of ENGAGEMENT_QUESTIONS) {
    const flag = got.questions?.[q.id];
    if (typeof flag === "boolean") questions[q.id] = flag;
  }
  const checkpoints = { ...base.checkpoints };
  const checkpointInterventions = { ...base.checkpointInterventions };
  for (const step of CHECKPOINTS) {
    const flag = got.checkpoints?.[step.id];
    if (typeof flag === "boolean") checkpoints[step.id] = flag;
    const listed = got.checkpointInterventions?.[step.id];
    if (Array.isArray(listed)) {
      const ids = listed.filter((id): id is InterventionId => isId(INTERVENTIONS.map((m) => m.id), id));
      if (ids.length) checkpointInterventions[step.id] = ids;
    }
  }
  const mappings = Array.isArray(got.mappings) ? got.mappings.map(readMapping).filter((row): row is MomentMapping => row !== null) : base.mappings;
  return {
    recordingSeconds: clampRecordingSeconds(typeof got.recordingSeconds === "number" ? got.recordingSeconds : base.recordingSeconds),
    questions,
    voiceSample: typeof got.voiceSample === "boolean" ? got.voiceSample : base.voiceSample,
    checkpoints,
    checkpointInterventions,
    mappings: mappings.length ? mappings : base.mappings,
    meetVisitors: got.meetVisitors === true,
  };
}

function emit(): void {
  if (typeof window !== "undefined") window.dispatchEvent(new Event("wlp-moment-config"));
}

export function readMomentConfig(): MomentConfig {
  if (typeof window === "undefined") return defaultMomentConfig();
  try {
    const raw = window.localStorage.getItem(MOMENT_CONFIG_KEY);
    if (!raw) return defaultMomentConfig();
    return normaliseMomentConfig(JSON.parse(raw));
  } catch {
    return defaultMomentConfig();
  }
}

export function saveMomentConfig(config: MomentConfig): MomentConfig {
  const next = normaliseMomentConfig(config);
  try {
    window.localStorage.setItem(MOMENT_CONFIG_KEY, JSON.stringify(next));
  } catch {
    /* a private window keeps the value this function returns */
  }
  emit();
  return next;
}

export function readSpeaker(): SpeakerMoment | null {
  if (typeof window === "undefined") return null;
  try {
    const raw = window.sessionStorage.getItem(MOMENT_SPEAKER_KEY);
    if (!raw) return null;
    const got = JSON.parse(raw) as Partial<SpeakerMoment>;
    return {
      answers: got.answers && typeof got.answers === "object" ? got.answers : {},
      voiceSample: got.voiceSample === true,
      recorded: got.recorded === true,
    };
  } catch {
    return null;
  }
}

export function saveSpeaker(next: SpeakerMoment): void {
  try {
    window.sessionStorage.setItem(MOMENT_SPEAKER_KEY, JSON.stringify(next));
  } catch {
    /* already gone with the tab */
  }
}

/** The speaker's answers and the placeholder reading. The host's settings stay. */
export function deleteSpeakerData(): void {
  try {
    window.sessionStorage.removeItem(MOMENT_SPEAKER_KEY);
  } catch {
    /* already gone */
  }
}

export type FiredIntervention = {
  intervention: InterventionId;
  moment: MomentId;
  intensity: number;
  shape: MatchShapeId;
};

export type CheckpointReading = {
  id: CheckpointId;
  title: string;
  fired: FiredIntervention[];
  quiet: InterventionId[];
};

/** Mappings the fixed placeholder would fire. Not a model result. */
export function placeholderFires(config: MomentConfig): FiredIntervention[] {
  return config.mappings
    .filter((row) => row.on && PLACEHOLDER_PATTERN[row.moment] >= row.threshold)
    .map((row) => ({
      intervention: row.intervention,
      moment: row.moment,
      intensity: row.intensity,
      shape: PLACEHOLDER_SHAPE,
    }));
}

/** Which mappings the fixed placeholder would fire. Not a model result. */
export function placeholderReading(config: MomentConfig): CheckpointReading[] {
  const fired = placeholderFires(config);
  return CHECKPOINTS.filter((step) => config.checkpoints[step.id]).map((step) => {
    const wanted = config.checkpointInterventions[step.id];
    const hits = fired.filter((row) => wanted.includes(row.intervention));
    const quiet = wanted.filter((id) => !hits.some((row) => row.intervention === id));
    return {
      id: step.id,
      title: step.title,
      fired: hits.map((row) => ({
        intervention: row.intervention,
        moment: row.moment,
        intensity: row.intensity,
        shape: PLACEHOLDER_SHAPE,
      })),
      quiet,
    };
  });
}

export function labelOf(kind: "moment" | "intervention", id: string): string {
  const rows = kind === "moment" ? MOMENTS : INTERVENTIONS;
  return rows.find((row) => row.id === id)?.label ?? id;
}
